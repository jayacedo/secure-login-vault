const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const { app, BrowserWindow } = require("electron");
const { testTempRoot } = require("./testTemp");
const root = fs.mkdtempSync(path.join(testTempRoot(), "activity-app-"));
app.setPath("userData", root); process.env.SLV_PIPE_USER = `activity-app-${process.pid}`;
require("../src/main");
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn) { for (let i = 0; i < 100; i++) { if (await fn()) return; await sleep(70); } throw Error("Activity UI timed out"); }
async function main() {
  await app.whenReady(); await until(() => BrowserWindow.getAllWindows().length);
  const win = BrowserWindow.getAllWindows()[0]; win.webContents.setBackgroundThrottling(false);
  win.show(); win.focus();
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once("did-finish-load", resolve));
  const run = code => win.webContents.executeJavaScript(code), api = code => run(`window.secureLoginVault.${code}`);
  assert.equal((await api("credentials.getActivityHistory()")).ok, false);
  const masterPassword = "Activity UI dummy master password";
  assert.equal((await api(`auth.createVault(${JSON.stringify({ masterPassword, confirmPassword: masterPassword })})`)).ok, true);
  await run("initAuth()");
  await run("document.querySelector('#activity-history-btn').click()");
  const ready = () => until(() => run("document.querySelector('#activity-results')?.getAttribute('aria-busy')==='false'"));
  await ready(); assert.match(await run("document.querySelector('#activity-status').textContent"), /No activity/);
  const data = { websiteName: "Client <img src=x onerror=alert(1)> portal", websiteUrl: "https://history.test", username: "Dummy-user", password: "Dummy-private-password", notes: "Dummy-private-note", groupName: "Client A" };
  const id = (await api(`credentials.add(${JSON.stringify(data)})`)).result.id;
  await api(`credentials.update(${id},${JSON.stringify({ ...data, password: "New-dummy-password" })})`);
  await api(`credentials.remove(${id})`);
  const trashId = (await api("credentials.getDeleted()")).result.entries[0].id;
  await api(`credentials.restoreDeleted(${trashId})`);
  await run("document.querySelector('#activity-refresh').click()"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 4);
  assert.equal(await run("document.querySelectorAll('#activity-results img').length"), 0);
  const text = await run("document.querySelector('#activity-results').textContent");
  for (const secret of [data.password, data.notes, data.username, "New-dummy-password"]) assert.equal(text.includes(secret), false);
  assert.match(text, /Desktop/); assert.match(text, /Login restored/);
  await run("document.documentElement.setAttribute('data-theme','dark')"); win.webContents.invalidate(); await sleep(500);
  fs.writeFileSync(path.join(root, "activity-dark.png"), (await win.webContents.capturePage()).toPNG());
  await run("document.querySelector('#activity-action').value='password_updated';document.querySelector('#activity-action').dispatchEvent(new Event('change'))"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 1);
  await run("document.querySelector('#activity-source').value='browser';document.querySelector('#activity-source').dispatchEvent(new Event('change'))"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 0);
  await run("document.querySelector('#activity-source').value='';document.querySelector('#activity-action').value='';document.querySelector('#activity-source').dispatchEvent(new Event('change'))"); await ready();
  await run("document.querySelector('#activity-search').value='no-match';document.querySelector('#activity-search').dispatchEvent(new Event('input'))");
  await until(() => run("document.querySelector('#activity-status').textContent.startsWith('No activity')"));
  await run("document.querySelector('#activity-search').value='Client A';document.querySelector('#activity-search').dispatchEvent(new Event('input'))");
  await until(() => run("document.querySelectorAll('.activity-entry').length===4"));
  win.setMinimumSize(400, 500); win.setSize(520, 760);
  await run("document.documentElement.setAttribute('data-theme','light')"); win.webContents.invalidate(); await sleep(500);
  assert.equal(await run("document.querySelector('#activity-history-overlay .modal-body').scrollWidth<=document.querySelector('#activity-history-overlay .modal-body').clientWidth+1"), true);
  fs.writeFileSync(path.join(root, "activity-narrow.png"), (await win.webContents.capturePage()).toPNG());
  await run("document.querySelector('#activity-close').focus();document.querySelector('#activity-close').dispatchEvent(new KeyboardEvent('keydown',{key:'Tab',shiftKey:true,bubbles:true}))");
  assert.equal(await run("document.activeElement.id"), "activity-done");
  await run("document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await run("document.querySelector('#activity-history-overlay').childElementCount"), 0);
  assert.equal(await run("document.activeElement.id"), "activity-history-btn");
  for (let i = 0; i < 51; i++) await api(`credentials.add(${JSON.stringify({ ...data, websiteName: `Pagination ${i}` })})`);
  await run("openActivityHistory()"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 50);
  await run("document.querySelector('#activity-next').click()"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 5);
  assert.equal(await run("document.querySelector('#activity-next').disabled"), true);
  await run("document.querySelector('#activity-prev').click()"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 50);
  await api('groups.add("Client B")'); await api('groups.setActive("Client B")');
  await run("openActivityHistory()"); await ready();
  assert.equal(await run("document.querySelectorAll('.activity-entry').length"), 0);
  assert.match(await run("document.querySelector('#activity-scope').textContent"), /Client B/);
  const child = new BrowserWindow({ show: false, webPreferences: { preload: path.join(__dirname, "../src/preload.js"), contextIsolation: true, sandbox: true } });
  await child.loadURL("about:blank");
  assert.equal((await child.webContents.executeJavaScript("window.secureLoginVault.credentials.getActivityHistory()")).ok, false); child.destroy();
  await run("handleLockVault()");
  assert.equal(await run("document.querySelector('#activity-history-overlay').childElementCount"), 0);
  assert.equal((await api("credentials.getActivityHistory()")).ok, false);
  console.log(`PASS History controls, empty state, filters/search, safe text, secret exclusion, group/sender/lock guards, keyboard focus and dark/narrow layouts\nScreenshots: ${root}`);
  app.exit(0);
}
setTimeout(() => { console.error("Activity UI timeout"); app.exit(1); }, 60000).unref();
main().catch(error => { console.error(error); app.exit(1); });
