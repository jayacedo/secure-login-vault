const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const { openEnvironment, prepareBrowserBundle, assertPrivateTree } = require('./slv-test-environment');
const { browserArguments, verifyRuntime } = require('./slv-test-browser');
const { fakeRegistry } = require('./browserSetupTestUtils');
const { testTempRoot } = require('./testTemp');
const registration = require('../src/native-host/registration');
const { getPipeName } = require('../src/native-host/pipeName');
const { createExtensionBridge } = require('../src/services/extensionBridge');
async function main() {
  const stage = fs.mkdtempSync(path.join(testTempRoot(), 'test-launcher-unit-'));
  const environment = openEnvironment(stage);
  assert.equal(openEnvironment(stage).pipeName, environment.pipeName, 'persistent test identity');
  assert.notEqual(environment.pipeName, getPipeName());
  assert.notEqual(environment.hostName, registration.HOST_NAME);
  assert.notEqual(environment.extensionId, require('../src/native-host/config').ALLOWED_EXTENSION_IDS[0]);
  const args = browserArguments(environment, 12345);
  assert.ok(args.includes('--user-data-dir=' + environment.paths.browser));
  assert.ok(args.includes('--disable-sync')); assert.throws(() => browserArguments(environment, 'bad'));
  const server = require('http').createServer((request, response) => {
    assert.equal(request.method, 'HEAD');
    response.writeHead(200, { 'X-SLV-Test-ID': environment.pipeUser }); response.end();
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    await verifyRuntime(environment, server.address().port);
    await assert.rejects(verifyRuntime({ ...environment, pipeUser: 'wrong-test' }, server.address().port), /not running/);
  } finally { await new Promise(resolve => server.close(resolve)); }
  const options = prepareBrowserBundle(environment, require('electron'));
  const registry = fakeRegistry(); await registration.register({ ...options, runReg: registry.runReg });
  assert.ok(registry.calls.every(call => call[1].endsWith('\\' + environment.hostName)));
  assert.equal((await registration.status({ ...options, runReg: registry.runReg })).browsers.every(b => b.ok), true);
  const manifest = JSON.parse(fs.readFileSync(path.join(environment.paths.extension, 'manifest.json')));
  assert.match(manifest.name, /TEST/); assert.deepEqual(manifest.optional_host_permissions, ['http://127.0.0.1/*']);
  assert.ok(fs.readFileSync(path.join(environment.paths.extension, 'status.js'), 'utf8').includes(environment.hostName));
  for (const name of ['offerSettings.js', 'inlineSettings.js', 'saveOffers.js', 'inlineFill.js']) {
    assert.ok(!fs.readFileSync(path.join(environment.paths.extension, name), 'utf8').includes('https://*/*'));
  }
  const launcherPath = path.join(options.installDir, environment.hostName + '.bat');
  const bridge = createExtensionBridge({ pipeName: environment.pipeName, handlers: { ping: () => ({ type: 'pong', appVersion: 'synthetic-test-only' }) } });
  await bridge.start();
  try {
    const rejected = await registration.selfTest({ launcherPath, origin: 'chrome-extension://' + require('../src/native-host/config').ALLOWED_EXTENSION_IDS[0] + '/' });
    assert.equal(rejected.error, 'origin-not-allowed');
    const reply = await registration.selfTest({ launcherPath, origin: 'chrome-extension://' + environment.extensionId + '/' });
    assert.equal(reply.appVersion, 'synthetic-test-only');
  } finally { await bridge.stop(); }
  const outside = path.join(stage, 'dummy-outside.txt'); fs.writeFileSync(outside, 'synthetic only');
  const link = path.join(environment.root, 'linked.txt'); fs.linkSync(outside, link);
  assert.throws(() => assertPrivateTree(environment.root), /linked/); fs.unlinkSync(link);
  const unmarked = path.join(stage, 'unmarked'); fs.mkdirSync(unmarked); fs.mkdirSync(path.join(unmarked, '.slv-test'));
  assert.throws(() => openEnvironment(unmarked), /ENOENT/);
  console.log('PASS test profile identity, explicit browser profile, separate registration/extension/pipe, production extension refusal, hard-link and unmarked-root rejection');
  // All data below stage was generated by this test; refuse linked paths first.
  assertPrivateTree(stage); fs.rmSync(stage, { recursive: true, force: true });
}
main().catch(error => { console.error(error); process.exitCode = 1; });
