const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const { app, BrowserWindow } = require("electron");
const { testTempRoot } = require("./testTemp");
const root = fs.mkdtempSync(path.join(testTempRoot(), "trash-app-"));
app.setPath("userData", root); process.env.SLV_PIPE_USER = `trash-app-${process.pid}`;
require("../src/main");
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, label) { for (let i = 0; i < 100; i++) { if (await fn()) return; await sleep(80); } throw Error(`Timed out: ${label}`); }
async function main() {
  await app.whenReady(); await until(() => BrowserWindow.getAllWindows().length, "window");
  const win = BrowserWindow.getAllWindows()[0]; win.webContents.setBackgroundThrottling(false);
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once("did-finish-load", resolve));
  const run = code => win.webContents.executeJavaScript(code), api = code => run(`window.secureLoginVault.${code}`);
  assert.equal((await api("credentials.getDeleted()")).ok, false);
  const masterPassword = "Recently deleted UI dummy password";
  await api(`auth.createVault(${JSON.stringify({ masterPassword, confirmPassword: masterPassword })})`);
  await run("initAuth()");
  const ready = () => until(() => run("document.querySelector('#trash-results')?.getAttribute('aria-busy')==='false'"), "trash ready");
  await run("document.querySelector('#recently-deleted-btn').click()"); await ready();
  assert.match(await run("document.querySelector('#trash-results').textContent"), /No recently deleted/);
  await run("closeCredentialTrash()");
  const first = { websiteName: "Client website", websiteUrl: "https://trash.test", username: "dummy-admin", password: "Old-UI-dummy-secret", groupName: "Client A" };
  const id = (await api(`credentials.add(${JSON.stringify(first)})`)).result.id;
  await api(`credentials.update(${id}, ${JSON.stringify({ ...first, password: "New-UI-dummy-secret" })})`);
  await run("refreshCredentials()");
  // Exercise the real row delete handler and its new recoverable-delete message.
  await run(`window.lastDeletePrompt='';window.confirm=message=>{window.lastDeletePrompt=message;return true};document.querySelector('[data-action="delete"][data-id="${id}"]').click()`);
  await until(async () => (await api("credentials.getAll()")).result.length === 0, "deleted from list");
  assert.match(await run("window.lastDeletePrompt"), /30 days/);
  const other = (await api(`credentials.add(${JSON.stringify({ ...first, websiteName: "<img src=x onerror=alert(1)>", groupName: "Client B" })})`)).result.id;
  await api(`credentials.remove(${other})`);
  await run("openCredentialTrash()"); await ready();
  assert.equal(await run("document.querySelectorAll('.trash-entry').length"), 2);
  assert.equal(await run("document.querySelectorAll('#trash-results img').length"), 0);
  assert.equal(await run("/Old-UI-dummy-secret|New-UI-dummy-secret/.test(document.querySelector('#trash-results').innerHTML)"), false);
  await run("document.querySelector('#toast-container')?.replaceChildren();document.documentElement.setAttribute('data-theme','dark')");
  await sleep(150); fs.writeFileSync(path.join(root, "recently-deleted.png"), (await win.webContents.capturePage()).toPNG());
  const entries = (await api("credentials.getDeleted()")).result.entries;
  const trashId = entries.find(entry => entry.websiteName === first.websiteName).id;
  await run(`document.querySelector('[data-trash-id="${trashId}"] [data-trash-action=restore]').click()`);
  await until(() => run("document.querySelectorAll('.trash-entry').length===1"), "restored list");
  assert.equal((await api(`credentials.getOne(${id})`)).result.password, "New-UI-dummy-secret");
  assert.equal((await api(`credentials.getPasswordHistory(${id})`)).result[0].password, first.password);
  const remainingId = (await api("credentials.getDeleted()")).result.entries[0].id;
  assert.equal((await api(`credentials.deletePermanently(${remainingId}, false)`)).ok, false);
  await run("document.querySelector('[data-trash-action=delete]').click()");
  assert.equal(await run("document.querySelector('[data-trash-action=cancel]')===document.activeElement"), true);
  await run("document.querySelector('[data-trash-action=cancel]').click()");
  assert.equal((await api("credentials.getDeleted()")).result.entries.length, 1);
  await run("document.querySelector('[data-trash-action=delete]').click()");
  win.setMinimumSize(400, 500); win.setSize(520, 720);
  await run("document.querySelector('#toast-container')?.replaceChildren();document.documentElement.setAttribute('data-theme','light')"); await sleep(180);
  assert.equal(await run("document.querySelector('#credential-trash-overlay .modal-body').scrollWidth <= document.querySelector('#credential-trash-overlay .modal-body').clientWidth+1"), true);
  fs.writeFileSync(path.join(root, "recently-deleted-narrow.png"), (await win.webContents.capturePage()).toPNG());
  await run("document.querySelector('[data-trash-action=confirm]').click()");
  await until(() => run("document.querySelector('#trash-results').textContent.includes('No recently deleted')"), "permanently deleted");
  await api(`credentials.remove(${id})`); await api('groups.setActive("Client B")');
  await run("openCredentialTrash()"); await ready();
  assert.equal(await run("document.querySelectorAll('.trash-entry').length"), 0);
  assert.match(await run("document.querySelector('#trash-scope').textContent"), /Client B/);
  const child = new BrowserWindow({ show: false, webPreferences: { preload: path.join(__dirname, "../src/preload.js"), contextIsolation: true, nodeIntegration: false, sandbox: true } });
  await child.loadURL("about:blank");
  for (const call of ["getDeleted()", "restoreDeleted(1)", "deletePermanently(1,true)"]) assert.equal((await child.webContents.executeJavaScript(`window.secureLoginVault.credentials.${call}`)).ok, false);
  child.destroy();
  await run("document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await run("document.querySelector('#credential-trash-overlay').childElementCount"), 0);
  await run("openCredentialTrash()"); await ready(); await run("handleLockVault()");
  assert.equal(await run("document.querySelector('#credential-trash-overlay').childElementCount"), 0);
  assert.equal((await api("credentials.getDeleted()")).ok, false);
  console.log(`PASS real delete/restore/history, safe metadata, permanent confirmation/cancel, empty/group states, narrow layout, IPC sender and lock cleanup\nScreenshots: ${root}`);
  app.exit(0);
}
setTimeout(() => { console.error("Trash UI timed out"); app.exit(1); }, 60000).unref();
main().catch(error => { console.error(error); app.exit(1); });
