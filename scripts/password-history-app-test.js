const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const { app, BrowserWindow } = require("electron");
const { testTempRoot } = require("./testTemp");
const root = fs.mkdtempSync(path.join(testTempRoot(), "history-app-"));
app.setPath("userData", root);
process.env.SLV_PIPE_USER = `history-app-${process.pid}`;
require("../src/main");
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, label) { for (let i = 0; i < 100; i++) { if (await fn()) return; await sleep(80); } throw Error(`Timed out: ${label}`); }
async function main() {
  await app.whenReady();
  await until(() => BrowserWindow.getAllWindows().length, "main window");
  const win = BrowserWindow.getAllWindows()[0];
  win.webContents.setBackgroundThrottling(false);
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once("did-finish-load", resolve));
  const run = code => win.webContents.executeJavaScript(code);
  const api = code => run(`window.secureLoginVault.${code}`);
  assert.equal((await api("credentials.getPasswordHistory(1)")).ok, false);
  const masterPassword = "history app test master password";
  await api(`auth.createVault(${JSON.stringify({ masterPassword, confirmPassword: masterPassword })})`);
  await run("initAuth()");
  const data = { websiteName: "Example client", websiteUrl: "https://example.test", username: "dummy", password: "Old-<dummy>&-password" };
  const id = (await api(`credentials.add(${JSON.stringify(data)})`)).result.id;
  const openHistory = async () => {
    await run(`openCredentialModal(${id})`);
    assert.equal(await run("document.querySelector('#password-history').open"), false);
    await run("document.querySelector('#password-history').open=true");
    await until(() => run("!document.querySelector('#password-history-list').textContent.includes('Loading') && document.querySelector('#password-history-list').textContent.length > 0"), "history loaded");
  };
  await openHistory();
  assert.match(await run("document.querySelector('#password-history-list').textContent"), /No previous/);
  await run("closeCredentialModal()");
  await api(`credentials.update(${id}, ${JSON.stringify({ ...data, password: "Current-dummy-password" })})`);
  await openHistory();
  assert.equal(await run("document.querySelector('.password-history-controls input').type"), "password");
  await run("document.querySelector('.password-history-controls button').click()");
  assert.equal(await run("document.querySelector('.password-history-controls input').type"), "text");
  assert.equal(await run("document.querySelector('.password-history-controls input').value"), data.password);
  await run("document.querySelector('.password-history-controls button').click()");
  await run("document.querySelector('.password-history-controls button:last-child').click()");
  assert.equal(await run("document.querySelector('#m-password').value"), data.password);
  assert.equal((await api(`credentials.getOne(${id})`)).result.password, "Current-dummy-password", "Use only stages the password");
  await run("document.querySelector('#modal-cancel-btn').click()");
  assert.equal(await run("document.querySelector('#credential-modal-overlay').childElementCount"), 0, "cancel removes secret DOM");
  await openHistory();
  await run("document.querySelector('.password-history-controls button:last-child').click();document.querySelector('#modal-save-btn').click()");
  await until(() => run("!document.querySelector('#credential-modal-overlay').classList.contains('is-open')"), "saved");
  assert.equal((await api(`credentials.getOne(${id})`)).result.password, data.password);
  assert.equal((await api(`credentials.getPasswordHistory(${id})`)).result[0].password, "Current-dummy-password");
  await openHistory();
  await run("document.querySelector('#gen-toggle-btn').click();document.querySelector('#password-history').scrollIntoView({block:'center'})");
  await run("document.querySelectorAll('.toast').forEach(element=>element.remove())");
  await sleep(150);
  fs.writeFileSync(path.join(root, "password-history.png"), (await win.webContents.capturePage()).toPNG());
  await run("document.querySelector('#password-history').open=false");
  await until(() => run("document.querySelector('#password-history-list').childElementCount===0"), "collapse clears secrets");
  await run("document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await run("document.querySelector('#credential-modal-overlay').childElementCount"), 0);
  const child = new BrowserWindow({ show: false, webPreferences: { preload: path.join(__dirname, "../src/preload.js"), contextIsolation: true, nodeIntegration: false, sandbox: true } });
  await child.loadURL("about:blank");
  assert.equal((await child.webContents.executeJavaScript(`window.secureLoginVault.credentials.getPasswordHistory(${id})`)).ok, false, "other renderers cannot read history");
  child.destroy();
  await openHistory();
  await run("handleLockVault()");
  await until(() => run("Boolean(document.querySelector('#unlock-vault-form'))"), "locked screen");
  assert.equal(await run("Boolean(document.querySelector('.password-history-controls'))"), false);
  assert.equal((await api(`credentials.getPasswordHistory(${id})`)).ok, false);
  console.log(`PASS history empty state, masked reveal, staged Use/Cancel/Save, escaping, collapse/close/lock cleanup and sender guard\nScreenshot: ${path.join(root, "password-history.png")}`);
  app.exit(0);
}
setTimeout(() => { console.error("History app test timed out"); app.exit(1); }, 60000).unref();
main().catch(error => { console.error(error); app.exit(1); });
