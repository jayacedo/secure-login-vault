const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const { app, BrowserWindow, dialog } = require("electron");
const { testTempRoot } = require("./testTemp");
const root = fs.mkdtempSync(path.join(testTempRoot(), "auto-backup-app-"));
const folder = path.join(root, "Chosen backups");fs.mkdirSync(folder);
app.setPath("userData",root);
process.env.SLV_PIPE_USER=`auto-backup-app-${process.pid}`;
dialog.showOpenDialog=async()=>({canceled:false,filePaths:[folder]});
require("../src/main");
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function until(fn,label){for(let i=0;i<100;i++){const value=await fn();if(value)return value;await sleep(80);}throw Error(`Timed out: ${label}`);}
async function main(){
  await app.whenReady();
  const win=await until(()=>BrowserWindow.getAllWindows()[0],"window");
  win.webContents.setBackgroundThrottling(false);
  if(win.webContents.isLoading())await new Promise(resolve=>win.webContents.once("did-finish-load",resolve));
  const run=code=>win.webContents.executeJavaScript(code);
  const api=code=>run(`window.secureLoginVault.${code}`);
  assert.equal((await api("settings.chooseAutomaticBackupFolder()")).ok,false,"locked folder changes refused");
  const password="automatic backup UI test password";
  assert.equal((await api(`auth.createVault(${JSON.stringify({masterPassword:password,confirmPassword:password})})`)).ok,true);
  await run("initAuth()");await run("openSettingsModal()");
  await until(()=>run("Boolean(document.querySelector('#auto-backup-choose'))"),"settings");
  await run("document.querySelector('#settings-tab-data').click()");
  await until(()=>run("!document.querySelector('#auto-backup-choose').disabled"),"backup status");
  assert.equal(await run("document.querySelector('#auto-backup-enabled').disabled"),true);
  await run("document.querySelector('#auto-backup-choose').click()");
  await until(()=>run("!document.querySelector('#auto-backup-enabled').disabled"),"chosen folder");
  assert.equal((await api("settings.getAutomaticBackups()")).result.enabled,false);
  assert.equal(fs.readdirSync(folder).length,0,"folder selection alone does not enable backups");
  await run("document.querySelector('#auto-backup-enabled').value='on';document.querySelector('#auto-backup-enabled').dispatchEvent(new Event('change'))");
  await until(()=>run("!document.querySelector('#auto-backup-now').disabled"),"enabled and first backup");
  assert.equal(fs.readdirSync(folder).filter(f=>f.endsWith('.slvbackup')).length,1);
  assert.match(await run("document.querySelector('#auto-backup-last').textContent"),/Last successful/);
  await run("document.querySelector('#auto-backup-now').click()");
  await until(()=>run("!document.querySelector('#auto-backup-now').disabled"),"manual backup finished");
  assert.equal(fs.readdirSync(folder).filter(f=>f.endsWith('.slvbackup')).length,2);
  assert.equal((await api('settings.configureAutomaticBackups({enabled:true,keep:30,folder:"C:/not-user-selected"})')).result.folder,folder,"renderer cannot change destination via settings payload");
  await run("closeSettingsModal();openSettingsModal()");
  await until(()=>run("document.querySelector('#auto-backup-keep').value==='30'"),"settings restored");
  await sleep(150);fs.writeFileSync(path.join(root,"automatic-backups.png"),(await win.webContents.capturePage()).toPNG());
  await api("settings.configureAutomaticBackups({enabled:false,keep:7})");
  await api("auth.lockVault()");
  assert.equal((await api("settings.runAutomaticBackup()")).ok,false);
  console.log(`PASS Settings choose/enable/backup-now, saved choices, native folder boundary and locked guards\nScreenshot: ${path.join(root,"automatic-backups.png")}`);
  app.exit(0);
}
setTimeout(()=>{console.error("Backup Settings test timed out");app.exit(1);},60000).unref();
main().catch(e=>{console.error(e);app.exit(1);});
