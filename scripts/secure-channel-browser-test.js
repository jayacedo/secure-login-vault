const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { app, BrowserWindow } = require("electron");
const { testTempRoot } = require("./testTemp");
const { createChannel } = require("../src/shared/secureChannel");
const root = fs.mkdtempSync(path.join(testTempRoot(), "secure-browser-"));
app.setPath("userData", root);
let win;
(async () => {
  await app.whenReady();
  win = new BrowserWindow({ show: false, webPreferences: { contextIsolation: true, nodeIntegration: false } });
  const fixture = path.join(root, "fixture.html");
  fs.writeFileSync(fixture, "<!doctype html><title>Local crypto fixture</title>");
  await win.loadFile(fixture);
  const run = code => win.webContents.executeJavaScriptInIsolatedWorld(1000, [{ code }]);
  await run(fs.readFileSync(path.join(__dirname, "../extension/secureChannel.js"), "utf8"));
  const secret = crypto.randomBytes(32);
  const nonceE = crypto.randomBytes(16).toString("hex"), nonceA = crypto.randomBytes(16).toString("hex");
  await run(`(async () => { globalThis.channel = await SLVSecureChannel.createChannel({secret: new Uint8Array(${JSON.stringify([...secret])}), nonceE:${JSON.stringify(nonceE)}, nonceA:${JSON.stringify(nonceA)}, role:"extension"}); })()`);
  const appChannel = await createChannel({ secret, nonceE, nonceA, role: "app", crypto: crypto.webcrypto });
  const packet = await run('channel.seal({type:"save-login",password:"browser-dummy"},"browser-id")');
  assert.deepEqual(await appChannel.open(packet), { type: "save-login", password: "browser-dummy" });
  const reply = await appChannel.seal({ ok: true, password: "app-dummy" }, "browser-id");
  assert.deepEqual(await run(`channel.open(${JSON.stringify(reply)})`), { ok: true, password: "app-dummy" });
  assert.equal(await run(`channel.open(${JSON.stringify(reply)}).then(()=>false,()=>true)`), true, "Chromium rejects replayed replies");
  console.log("PASS actual Chromium Web Crypto <-> desktop Web Crypto encryption and replay rejection");
  win.destroy(); app.exit(0);
})().catch(error => { console.error(error); win?.destroy(); app.exit(1); });
